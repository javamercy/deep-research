import operator
from collections.abc import Sequence
from typing import Annotated, TypedDict

from langchain_core.messages import BaseMessage
from langgraph.graph import MessagesState, add_messages

from deep_research.schemas import ResearchPlan


class AgentInputState(MessagesState):
    """Input state for the full agent - only contains messages from user input."""
    pass


class AgentState(MessagesState):
    """
    Main state for the full multi-agent research system.

    Extends MessagesState with additional fields for research coordination.
    Note: Some fields are duplicated across different state classes for proper
    state management between subgraphs and the main workflow.

    Attributes:
        research_brief (str): The research brief generated from user input.
        research_plan (ResearchPlan): The structured research plan derived from the research brief.
        supervisor_messages (Sequence[BaseMessage]): Messages exchanged with the supervisor agent.
        raw_notes (list[str]): Raw unprocessed notes collected during research.
        notes (list[str]): Processed and structured notes ready for final report generation.
        final_report (str): The final report generated after research completion.
    """

    research_brief: str
    research_plan: ResearchPlan
    supervisor_messages: Annotated[Sequence[BaseMessage], add_messages]
    raw_notes: Annotated[list[str], operator.add]
    notes: Annotated[list[str], operator.add]
    final_report: str


class ScopingInputState(MessagesState):
    """Input state for the scoping agent - only contains messages from user input."""
    pass


class ScopingState(MessagesState):
    """State for the scoping agent containing message history and research metadata.

    Tracks the scoping agent's conversation, research brief, research plan,
    and planning iterations for limiting the number of planning cycles.

    Attributes:
        clarification_question (str): The clarification question generated by the scoping agent.
        research_brief (str): The research brief generated from user input.
        research_plan (ResearchPlan): The structured research plan derived from the research brief.
        plan_feedback (str): Feedback on the research plan provided by the user or supervisor.
        plan_approved (bool): Whether the research plan is approved or not.
        planning_iterations (int): Counter tracking the number of planning iterations performed.
    """

    clarification_question: str
    research_brief: str
    research_plan: ResearchPlan
    plan_feedback: str
    plan_approved: bool
    planning_iterations: int


class ScopingOutputState(TypedDict):
    """Output state for the scoping agent's output containing the research brief and plan.

    Attributes:
        research_brief (str): The research brief generated from user input.
        research_plan (ResearchPlan): The structured research plan derived from the research brief.
    """

    research_brief: str
    research_plan: ResearchPlan


class ResearcherInputState(TypedDict):
    """Input state for the research agent containing message history and research metadata.

    Attributes:
        researcher_messages (Sequence[BaseMessage]): Messages exchanged with the research agent.
        research_topic (str): The research topic being investigated.
        researcher_tool_calls (int): Counter tracking the number of tool calls made by the researcher.
    """

    researcher_messages: Annotated[Sequence[BaseMessage], add_messages]
    research_topic: str
    researcher_tool_calls: int


class ResearcherState(TypedDict):
    """State for the research agent containing message history and research metadata.

    This state tracks the researcher's conversation, iteration count for limiting
    tool calls, the research topic being investigated, compressed findings,
    and raw research notes for detailed analysis.

    Attributes:
        researcher_messages (Sequence[BaseMessage]): Messages exchanged with the research agent.
        research_topic (str): The research topic being investigated.
        researcher_tool_calls (int): Counter tracking the number of tool calls made by the researcher.
        compressed_research (str): Compressed summary of the research findings.
        raw_notes (list[str]): Raw unprocessed notes collected during research for detailed analysis.
    """

    researcher_messages: Annotated[Sequence[BaseMessage], add_messages]
    research_topic: str
    researcher_tool_calls: int
    compressed_research: str
    raw_notes: Annotated[list[str], operator.add]


class ResearcherOutputState(TypedDict):
    """Output state for the research agent containing final research results.

    This represents the final output of the research process with compressed
    research findings and all raw notes from the research process.
    """

    researcher_messages: Annotated[Sequence[BaseMessage], add_messages]
    raw_notes: Annotated[list[str], operator.add]
    compressed_research: str


class SupervisorInputState(TypedDict):
    """Input state for the multi-agent research supervisor.

    Attributes:
        supervisor_messages (Sequence[BaseMessage]): Messages exchanged with the supervisor for coordination and decision-making
    """

    research_plan: ResearchPlan


class SupervisorState(TypedDict):
    """State for the multi-agent research supervisor.

    Manages coordination between supervisor and research agents, tracking
    research progress and accumulating findings from multiple sub-agents.

    Attributes:
        supervisor_messages (Sequence[BaseMessage]): Messages exchanged with the supervisor for coordination and decision-making
        research_plan (ResearchPlan): The structured research plan derived from the research brief.
        notes (list[str]): Processed and structured notes ready for final report generation.
        supervisor_iterations (int): Counter tracking the number of iterations performed by the supervisor.
        raw_notes (list[str]): Raw unprocessed notes collected during research for detailed analysis.
    """

    supervisor_messages: Annotated[Sequence[BaseMessage], add_messages]
    research_plan: ResearchPlan
    notes: Annotated[list[str], operator.add]
    supervisor_iterations: int
    raw_notes: Annotated[list[str], operator.add]


class SupervisorOutputState(TypedDict):
    """Output state for the multi-agent research supervisor.

    Attributes:
        research_plan (ResearchPlan): The structured research plan derived from the research brief.
        notes (list[str]): Processed and structured notes ready for final report generation.
    """
    
    research_plan: ResearchPlan
    notes: Annotated[list[str], operator.add]
