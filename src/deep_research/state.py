"""LangGraph state schemas, reducers, and validated channel aliases for each workflow.

`ValidatedResearchPlan` and `ValidatedDraftResearch` use `ValidatedLastValue`
so JSON dicts arriving from Studio/HTTP inputs, state edits, or checkpoints are
coerced into `ResearchPlan` and `DraftResearch` instances before storage.
"""

import operator
from collections.abc import Sequence
from typing import Annotated, TypedDict

from langchain_core.messages import BaseMessage
from langgraph.graph import MessagesState, add_messages

from deep_research.channels import ValidatedLastValue
from deep_research.schemas import DraftResearch, ResearchPlan

# Implicit aliases (not PEP 695 `type`) so LangGraph sees `Annotated.__metadata__` at runtime.
ValidatedResearchPlan = Annotated[ResearchPlan, ValidatedLastValue]
ValidatedDraftResearch = Annotated[DraftResearch, ValidatedLastValue]


class AgentInputState(MessagesState):
    """Entry input schema for `deep_research_graph`, accepting only `messages`."""


class AgentState(MessagesState):
    """Top-level state shared across `scoping_graph`, `supervisor_graph`, and `writer_graph`.

    Inherits `messages` with the `add_messages` reducer from `MessagesState`
    so user queries, clarification turns, and the final report `AIMessage` share
    a single conversation history. Subgraph inputs and outputs exchange matching
    keys automatically across the parent graph.

    Attributes:
        research_brief: Detailed research question produced by `scoping_graph`
            and read by `writer_graph`.
        research_plan: Structured research plan produced during scoping and
            updated during supervision; uses `ValidatedLastValue` to coerce
            JSON payloads into `ResearchPlan`.
        supervisor_messages: Supervisor tool-calling conversation using
            `add_messages` to append and update messages by ID.
        compressed_researches: `(research_topic, compressed_research)` pairs
            accumulated with `operator.add` so successive updates append rather
            than overwrite.
        final_report: Markdown report produced by `writer_graph`, finalized
            with numbered citations and a `### Sources` bibliography.
    """

    research_brief: str
    research_plan: ValidatedResearchPlan
    supervisor_messages: Annotated[Sequence[BaseMessage], add_messages]
    compressed_researches: Annotated[list[tuple[str, str]], operator.add]
    final_report: str


class ScopingInputState(MessagesState):
    """Entry input schema for `scoping_graph`, accepting only `messages`."""


class ScopingState(MessagesState):
    """Internal state for `scoping_graph` spanning clarification and plan review.

    Inherits `messages` with the `add_messages` reducer from `MessagesState` to
    append clarification turns and the pre-research verification message.

    Attributes:
        clarification_question: Question generated by `assess_clarification` and
            surfaced to the user via `interrupt()` in `ask_clarification`.
        research_brief: Concrete research question synthesized by
            `write_research_brief`.
        research_plan: Proposed or revised `ResearchPlan`, wrapped in
            `ValidatedLastValue` to coerce JSON payloads on edits and
            checkpoints.
        plan_feedback: Revision feedback returned by the `review_plan`
            interrupt and consumed by `create_plan`.
        plan_approved: Approval flag from the latest `review_plan` response.
        planning_iterations: Number of `create_plan` passes completed;
            `review_plan` stops revising once `max_planning_iterations` is
            reached.
    """

    clarification_question: str
    research_brief: str
    research_plan: ValidatedResearchPlan
    plan_feedback: str
    plan_approved: bool
    planning_iterations: int


class ScopingOutputState(MessagesState):
    """Output schema emitted by `scoping_graph` to downstream workflows.

    Inherits `messages` (`add_messages` reducer) so clarification turns and any
    verification acknowledgement propagate back to `AgentState`.

    Attributes:
        research_brief: Concrete research question consumed by `writer_graph`.
        research_plan: Approved (or max-iteration) `ResearchPlan` coerced via
            `ValidatedLastValue` for `supervisor_graph`.
    """

    research_brief: str
    research_plan: ValidatedResearchPlan


class ResearcherInputState(TypedDict):
    """Input schema for `researcher_graph`, launched per `ConductResearch` call.

    Attributes:
        researcher_messages: Seed message list (typically a `HumanMessage`
            containing the assigned topic), using `add_messages` to append or
            update messages by ID.
        research_topic: Focused topic string investigated by this researcher
            and passed to `compress_research`.
    """

    researcher_messages: Annotated[Sequence[BaseMessage], add_messages]
    research_topic: str


class ResearcherState(TypedDict):
    """Internal state for a single `researcher_graph` execution.

    Attributes:
        researcher_messages: Search and reasoning conversation between
            `conduct_research` and `researcher_tools`, merged via
            `add_messages`.
        research_topic: Topic assigned by the supervisor and passed to
            `compress_research`.
        researcher_tool_calls: Cumulative count of tool calls dispatched by
            `researcher_tools`; once it reaches `max_researcher_tool_calls`,
            `conduct_research` routes directly to `compress_research`.
        draft_research: Structured `DraftResearch` produced by
            `compress_research` with assigned finding IDs, wrapped in
            `ValidatedLastValue` to coerce JSON payloads on edits or
            checkpoints.
        compressed_research: Verified Markdown summary with `[source_id]`
            citations and a `### Sources` list formatted by `verify_research`.
    """

    researcher_messages: Annotated[Sequence[BaseMessage], add_messages]
    research_topic: str
    researcher_tool_calls: int
    draft_research: ValidatedDraftResearch
    compressed_research: str


class ResearcherOutputState(TypedDict):
    """Output schema for `researcher_graph`, exposing only `compressed_research`.

    Isolates internal `researcher_messages`, `researcher_tool_calls`, and
    `draft_research` from `supervisor_graph`.

    Attributes:
        compressed_research: Verified, citation-formatted Markdown findings
            returned as the `ConductResearch` tool observation.
    """

    compressed_research: str


class SupervisorInputState(TypedDict):
    """Entry input schema for `supervisor_graph`.

    Attributes:
        research_plan: Initial `ResearchPlan` to execute, wrapped in
            `ValidatedLastValue` to coerce JSON payloads from external callers
            or parent state.
    """

    research_plan: ValidatedResearchPlan


class SupervisorState(TypedDict):
    """Internal state for `supervisor_graph` coordinating parallel researchers.

    Attributes:
        supervisor_messages: Tool-calling conversation between `supervisor` and
            `supervisor_tools`, merged via `add_messages`.
        research_plan: Active `ResearchPlan` updated in place by
            `UpdateResearchPlan` tool calls and coerced via
            `ValidatedLastValue`.
        compressed_researches: `(research_topic, compressed_research)` pairs
            returned by `ConductResearch` subgraphs, accumulated with
            `operator.add` across iterations.
        supervisor_iterations: Number of `supervisor` turns executed; stops the
            loop when `max_supervisor_iterations` is reached.
    """

    supervisor_messages: Annotated[Sequence[BaseMessage], add_messages]
    research_plan: ValidatedResearchPlan
    compressed_researches: Annotated[list[tuple[str, str]], operator.add]
    supervisor_iterations: int


class SupervisorOutputState(TypedDict):
    """Output schema emitted by `supervisor_graph` after `ResearchComplete` or max iterations.

    Attributes:
        research_plan: Final `ResearchPlan` with updated task statuses, coerced
            via `ValidatedLastValue`.
        compressed_researches: Accumulated `(research_topic,
            compressed_research)` pairs annotated with `operator.add` to match
            the additive reducer on `SupervisorState` and `AgentState`.
    """

    research_plan: ValidatedResearchPlan
    compressed_researches: Annotated[list[tuple[str, str]], operator.add]


class WriterInputState(TypedDict):
    """Entry input schema for `writer_graph`.

    Does not inherit `MessagesState`, so upstream scoping messages are not
    passed into the writer.

    Attributes:
        research_brief: Target research question guiding report synthesis and
            review.
        compressed_researches: Verified `(research_topic, compressed_research)`
            pairs from `supervisor_graph`, annotated with `operator.add` to
            match `AgentState`.
    """

    research_brief: str
    compressed_researches: Annotated[list[tuple[str, str]], operator.add]


class WriterState(MessagesState):
    """Internal state for `writer_graph` across drafting and review iterations.

    Inherits `messages` (`add_messages` reducer) from `MessagesState`; only the
    finalized report is appended as an `AIMessage` when `review_report` ends.

    Attributes:
        research_brief: Target research question read by `write_report` and
            `review_report`.
        compressed_researches: Verified `(research_topic, compressed_research)`
            pairs annotated with `operator.add` to match `WriterInputState`.
        writer_iterations: Count of rejected drafts sent back to `write_report`;
            once `max_report_reviewer_iterations` is reached, `review_report`
            skips LLM review and finalizes the current draft.
        report_review: XML-serialized `FinalReportReview` returned by
            `review_report` on rejection and included in the next
            `write_report` prompt.
        final_report: Draft Markdown report with `[source_id]` tags during
            revisions, replaced upon completion with numbered citations and an
            appended `### Sources` list.
    """

    research_brief: str
    compressed_researches: Annotated[list[tuple[str, str]], operator.add]
    writer_iterations: int
    report_review: str
    final_report: str


class WriterOutputState(MessagesState):
    """Output schema emitted by `writer_graph` when the report is finalized.

    Inherits `messages` (`add_messages` reducer) so the finalized report
    `AIMessage` propagates back to `AgentState` alongside `final_report`.

    Attributes:
        final_report: Final Markdown report with numbered citations and an
            appended `### Sources` bibliography.
    """

    final_report: str
